/**
 * Stands up, seeds and tears down the pen-test deployment (pen test E1, #87, and E2, #88), and writes the credentials
 * package (E4, #90). Run as `pnpm pen-test:up`, `pnpm pen-test:seed`, `pnpm pen-test:credentials` and
 * `pnpm pen-test:down`, from the root of the repo. docs/pen-test/deployment.md is the runbook.
 *
 * It never reads production's secrets: every secret it uses is generated into `.pen-test-deployment/`, Compose is always
 * given that folder's `.env` with `--env-file`, so the root `.env` is never read, and Docker is run with only the
 * variables the Docker client needs, so nothing exported in the shell reaches Compose.
 */
import { spawnSync, type SpawnSyncReturns } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync } from "node:fs";
import { chmod, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import {
  databaseRoles,
  loginRoles,
  type DatabaseRolePasswords,
} from "../../lib/database-roles.js";
import {
  deriveFixtureCredentials,
  userHandles,
} from "../fixtures/fixture-plan.js";
import {
  penTestAppUrl,
  penTestMailUrl,
  penTestProjectName,
  penTestStateDirectory,
} from "./project.js";
import { credentialVariableName } from "./sign-in.js";

const root = resolve(".");
const state = join(root, penTestStateDirectory);
const envFile = join(state, ".env");
const rcloneConfigFile = join(state, "rclone.conf");
const ageIdentityFile = join(state, "age-identity.txt");
const fixtureSeedFile = join(state, "fixture-seed.txt");
const credentialsPackageFile = join(state, "credentials-package.env");

/** The only variables Docker is given: enough for the client to find its daemon, and nothing else. */
const dockerVariableNames = [
  "PATH",
  "HOME",
  "USER",
  "TMPDIR",
  "DOCKER_HOST",
  "DOCKER_CONTEXT",
  "DOCKER_CONFIG",
  "DOCKER_CERT_PATH",
  "DOCKER_TLS_VERIFY",
  "XDG_RUNTIME_DIR",
] as const;

export const dockerEnvironment = (
  from: NodeJS.ProcessEnv = process.env,
): Record<string, string> =>
  Object.fromEntries(
    dockerVariableNames.flatMap((name) => {
      const value = from[name];
      return value === undefined ? [] : [[name, value]];
    }),
  );

/** The arguments that make `docker compose` name the pen-test project, its own .env and both files. */
export const composeArguments = (environmentFile = envFile): string[] => [
  "compose",
  "--project-name",
  penTestProjectName,
  "--env-file",
  environmentFile,
  "--file",
  "docker-compose.yml",
  "--file",
  "docker-compose.pen-test.yml",
];

interface RunOptions {
  input?: string;
  isQuiet?: boolean;
}

const run = (
  command: string,
  args: readonly string[],
  { input, isQuiet = false }: RunOptions = {},
): SpawnSyncReturns<string> => {
  const result = spawnSync(command, args, {
    cwd: root,
    env: dockerEnvironment(),
    encoding: "utf8",
    input,
    stdio: [input === undefined ? "inherit" : "pipe", "pipe", "pipe"],
    maxBuffer: 64 * 1024 * 1024,
  });
  if (!isQuiet) {
    process.stderr.write(result.stderr);
  }
  return result;
};

const runOrFail = (
  command: string,
  args: readonly string[],
  options: RunOptions = {},
): string => {
  const result = run(command, args, options);
  if (result.status !== 0) {
    if (options.isQuiet === true) {
      process.stderr.write(result.stderr);
    }
    throw new Error(
      `${command} ${args.slice(0, 8).join(" ")} … failed with exit code ${String(result.status)}`,
    );
  }
  return result.stdout;
};

const compose = (args: readonly string[], options: RunOptions = {}) =>
  runOrFail("docker", [...composeArguments(), ...args], options);

const writePrivate = async (path: string, content: string) => {
  await writeFile(path, content, { mode: 0o600 });
  await chmod(path, 0o600);
};

/** The variable docker-compose.yml reads a login role's password from, such as DATABASE_API_PASSWORD. */
export const databasePasswordVariable = (
  role: keyof DatabaseRolePasswords,
): string => `DATABASE_${role.toUpperCase()}_PASSWORD`;

/** The same placeholder for every database password, for rendering an .env Compose only reads. */
export const placeholderDatabasePasswords = (
  value: string,
): DatabaseRolePasswords => ({
  migrate: value,
  api: value,
  worker: value,
  backup: value,
});

/** The deployment's .env: generated secrets only, and the throwaway backup targets. */
export const renderEnvFile = ({
  postgresPassword,
  databasePasswords,
  encryptionKey,
  ageRecipient,
}: {
  postgresPassword: string;
  databasePasswords: DatabaseRolePasswords;
  encryptionKey: string;
  ageRecipient: string;
}): string =>
  [
    "# The pen-test deployment's own secrets, generated by pnpm pen-test:up. Never production's.",
    `POSTGRES_PASSWORD=${postgresPassword}`,
    ...loginRoles.map(
      (role) => `${databasePasswordVariable(role)}=${databasePasswords[role]}`,
    ),
    `APP_URL=${penTestAppUrl}`,
    `ENCRYPTION_KEY=${encryptionKey}`,
    `BACKUP_AGE_RECIPIENT=${ageRecipient}`,
    "BACKUP_RCLONE_REMOTE=stand-in:/srv/backup-stand-in/email-platform",
    `BACKUP_RCLONE_CONFIG_FILE=./${penTestStateDirectory}/rclone.conf`,
    `BACKUP_AGE_IDENTITY_FILE=./${penTestStateDirectory}/age-identity.txt`,
    "BACKUP_KEEP_DAYS=14",
    "BACKUP_HOUR_UTC=2",
    "",
  ].join("\n");

/** A local rclone remote: the throwaway stand-in for the real one, a folder on a volume of the deployment's own. */
export const standInRcloneConfig = "[stand-in]\ntype = local\n";

const readEnvValue = (content: string, name: string): string | undefined =>
  new RegExp(`^${name}=(.*)$`, "mu").exec(content)?.[1];

const writeSecrets = async () => {
  await mkdir(state, { recursive: true, mode: 0o700 });
  await chmod(state, 0o700);
  if (existsSync(envFile)) {
    const content = await readFile(envFile, "utf8");
    if (
      !(readEnvValue(content, "BACKUP_AGE_RECIPIENT") ?? "").startsWith("age1")
    ) {
      throw new Error(
        `${envFile} has no age recipient. Run pnpm pen-test:down and stand it up again`,
      );
    }
    // A deployment stood up before each container had a role of its own (#121) has no passwords for them.
    if (readEnvValue(content, databasePasswordVariable("api")) === undefined) {
      throw new Error(
        `${envFile} has no password for ${databaseRoles.api}. Run pnpm pen-test:down and stand it up again`,
      );
    }
    return;
  }
  const newPassword = () => randomBytes(24).toString("base64url");
  const secrets = {
    postgresPassword: newPassword(),
    databasePasswords: {
      migrate: newPassword(),
      api: newPassword(),
      worker: newPassword(),
      backup: newPassword(),
    },
    encryptionKey: randomBytes(32).toString("base64"),
  };
  await writePrivate(rcloneConfigFile, standInRcloneConfig);
  // Compose needs every variable to read the files at all, so the recipient is a placeholder until the key exists.
  await writePrivate(
    envFile,
    renderEnvFile({ ...secrets, ageRecipient: "not-made-yet" }),
  );
  compose(["build", "backup"]);
  const identity = compose(
    ["run", "--rm", "--no-deps", "-T", "backup", "age-keygen"],
    { isQuiet: true },
  );
  const ageRecipient = /^# public key: (age1[0-9a-z]+)$/mu.exec(identity)?.[1];
  if (ageRecipient === undefined) {
    throw new Error("age-keygen gave no public key");
  }
  await writePrivate(ageIdentityFile, identity);
  await writePrivate(envFile, renderEnvFile({ ...secrets, ageRecipient }));
};

const up = async () => {
  await writeSecrets();
  compose(["up", "--detach", "--build", "--wait", "--remove-orphans"]);
  process.stdout.write(
    `The pen-test deployment ${penTestProjectName} is up at ${penTestAppUrl}, and its mail at ${penTestMailUrl}\n`,
  );
};

const readSeed = async (): Promise<string> => {
  if (!existsSync(fixtureSeedFile)) {
    await writePrivate(
      fixtureSeedFile,
      `${randomBytes(32).toString("base64url")}\n`,
    );
  }
  return (await readFile(fixtureSeedFile, "utf8")).trim();
};

const seed = async () => {
  if (!existsSync(envFile)) {
    throw new Error("The deployment isn't up: run pnpm pen-test:up first");
  }
  const fixtureSeed = await readSeed();
  const output = compose(
    [
      "exec",
      "-T",
      "api",
      "node",
      "dist/src/pen-test/fixtures/load-fixtures-command.js",
    ],
    { input: `${fixtureSeed}\n` },
  );
  process.stdout.write(output);
};

/** The credentials package: every fixture credential as an environment variable, for the harness to read. */
export const renderCredentialsPackage = (fixtureSeed: string): string => {
  const credentials = deriveFixtureCredentials(fixtureSeed);
  return [
    "# The pen-test credentials package (E4). Synthetic, and works only on the pen-test deployment until it is torn down.",
    "# Never commit it, paste it into an issue or a prompt, or pass one of its values as a command-line argument.",
    `PEN_TEST_URL=${penTestAppUrl}`,
    ...userHandles.map(
      (handle) =>
        `${credentialVariableName("user", handle)}=${credentials.passwords[handle]}`,
    ),
    ...Object.entries(credentials.apiKeys).map(
      ([handle, secret]) =>
        `${credentialVariableName("key", handle)}=${secret}`,
    ),
    "",
  ].join("\n");
};

const credentialsPackage = async () => {
  if (!existsSync(fixtureSeedFile)) {
    throw new Error(
      "There is no fixture seed yet: run pnpm pen-test:seed first",
    );
  }
  const fixtureSeed = (await readFile(fixtureSeedFile, "utf8")).trim();
  await writePrivate(
    credentialsPackageFile,
    renderCredentialsPackage(fixtureSeed),
  );
  process.stdout.write(
    `Wrote the credentials package for ${String(userHandles.length)} Users and 3 API Keys to ${credentialsPackageFile}, readable only by you. None of it is printed.\n`,
  );
};

const listLabelled = (kind: "container" | "volume" | "network"): string[] => {
  const args =
    kind === "container" ? ["ps", "--all", "--quiet"] : [kind, "ls", "--quiet"];
  return runOrFail(
    "docker",
    [
      ...args,
      "--filter",
      `label=com.docker.compose.project=${penTestProjectName}`,
    ],
    { isQuiet: true },
  )
    .split("\n")
    .filter((line) => line.trim() !== "");
};

const down = async () => {
  const before = {
    containers: listLabelled("container").length,
    volumes: listLabelled("volume").length,
    networks: listLabelled("network").length,
  };
  // Compose must be able to read the files to take them down, whether or not this deployment's .env survived.
  const environmentFile = existsSync(envFile)
    ? envFile
    : join(root, "docker-compose.pen-test.placeholder.env");
  if (environmentFile !== envFile) {
    await writeFile(
      environmentFile,
      renderEnvFile({
        postgresPassword: "placeholder",
        databasePasswords: placeholderDatabasePasswords("placeholder"),
        encryptionKey: "placeholder",
        ageRecipient: "placeholder",
      }),
    );
  }
  try {
    runOrFail("docker", [
      ...composeArguments(environmentFile),
      // The restore profile's containers, from a `run` of a restore, are the project's too.
      "--profile",
      "restore",
      "down",
      "--volumes",
      "--remove-orphans",
      "--timeout",
      "5",
    ]);
  } finally {
    if (environmentFile !== envFile) {
      await rm(environmentFile, { force: true });
    }
  }
  const left = {
    containers: listLabelled("container"),
    volumes: listLabelled("volume"),
    networks: listLabelled("network"),
  };
  const leftOver = Object.entries(left).filter(([, ids]) => ids.length > 0);
  process.stdout.write(
    `Removed ${String(before.containers)} containers, ${String(before.volumes)} volumes and ${String(before.networks)} networks of ${penTestProjectName}.\n`,
  );
  if (leftOver.length > 0) {
    throw new Error(
      `Still left with the ${penTestProjectName} label: ${leftOver.map(([kind, ids]) => `${kind} ${ids.join(", ")}`).join("; ")}`,
    );
  }
  process.stdout.write(
    `No container, volume or network labelled ${penTestProjectName} is left.\n`,
  );
  await rm(state, { recursive: true, force: true });
  process.stdout.write(
    `Deleted ${state}, with the deployment's secrets, fixture seed, credentials package and backup key.\n`,
  );
};

const commands: Record<string, () => Promise<void>> = {
  up,
  down,
  seed,
  credentials: credentialsPackage,
};

const isMain =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === resolve(import.meta.filename);

if (isMain) {
  const command = commands[process.argv[2] ?? ""];
  if (command === undefined) {
    process.stderr.write(`Run one of: ${Object.keys(commands).join(", ")}\n`);
    process.exitCode = 1;
  } else {
    try {
      await command();
    } catch (error) {
      process.stderr.write(
        `${error instanceof Error ? error.message : String(error)}\n`,
      );
      process.exitCode = 1;
    }
  }
}
